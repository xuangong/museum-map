"""Build src/data/dynasty-territory.ts from Cliopatria (CC BY 4.0, Seshat Global History Databank).

One-shot data tool — the app never runs it. Needs Python 3 with shapely (`pip install shapely` in a venv).
Data: download cliopatria.geojson from https://github.com/Seshat-Global-History-Databank/cliopatria
into its own empty directory and pass the path in (don't run the script from inside that directory).

Usage: <venv>/bin/python -I scripts/build-territories.py <cliopatria.geojson> src/data/dynasty-territory.ts \
         [<preview.svg> <china-outline.geojson>]
The optional preview draws every layer over today's outline for a visual check.

Per dynasty layer: one representative year, clipped to 70–137°E / 15–55°N, simplified.
Divided eras keep one part per regime (labelled in the UI).
Editorial changes (also stated in the generated file header):
  - 明: adds the Tibetan plateau (乌斯藏·朵甘都司) following 谭其骧《中国历史地图集》 —
        taken as Cliopatria's Qing (1820) extent inside a plateau outline, merged into Ming.
  - 夏: no polity in the dataset — a hand-sketched 二里头文化 core area.
"""
import json
import math
import sys

from shapely.geometry import Polygon, MultiPolygon, box, shape
from shapely.ops import unary_union

src_path, out_ts = sys.argv[1], sys.argv[2]
preview = sys.argv[3] if len(sys.argv) > 3 else None
china_path = sys.argv[4] if len(sys.argv) > 4 else None

TARGETS = {
    "shang": (-1250, [("Shang Dynasty", "商")]),
    "western-zhou": (-900, [("Zhou Dynasty", "西周")]),
    "eastern-zhou": (-300, [("(Warring States China)", "战国诸国")]),
    "qin": (-210, [("Qin Dynasty", "秦")]),
    "western-han": (-100, [("Han Dynasty", "西汉")]),
    "eastern-han": (100, [("Han Dynasty", "东汉")]),
    "three-kingdoms": (250, [("Cao Wei", "曹魏"), ("Shu Han", "蜀汉"), ("Eastern Wu", "孙吴")]),
    "jin": (290, [("Western Jin", "西晋")]),
    "nanbeichao": (500, [("Northern Wei", "北魏"), ("Southern Qi", "南齐")]),
    "sui": (610, [("Sui Dynasty", "隋")]),
    "tang": (700, [("Tang Dynasty", "唐")]),
    "wudai": (950, [("(Five Dynasties and Ten Kingdoms)", "五代十国")]),
    "song": (1100, [("Northern Song", "北宋")]),
    "liao": (1050, [("Liao Dynasty", "辽")]),
    "jin-jurchen": (1180, [("Great Jin", "金")]),
    "yuan": (1300, [("Yuan Dynasty", "元")]),
    "ming": (1500, [("Ming Dynasty", "明")]),
    "qing": (1820, [("Qing Dynasty", "清")]),
}
XIA = [(110.5, 34.1), (110.9, 35.2), (111.6, 35.9), (112.5, 36.1), (113.4, 35.6), (113.9, 34.8),
       (113.7, 34.0), (112.9, 33.6), (111.7, 33.6)]
# Tibetan plateau outline used to take 乌斯藏·朵甘 from the Qing extent (outer edges come from Qing).
PLATEAU = Polygon([(78.0, 35.7), (80.5, 36.0), (86.0, 36.3), (90.5, 36.6), (94.0, 37.2), (97.0, 38.4),
                   (100.8, 38.6), (103.2, 36.6), (103.6, 33.4), (102.7, 29.4), (100.4, 26.8), (98.4, 27.4),
                   (96.5, 28.0), (93.0, 26.5), (88.0, 26.5), (84.0, 27.5), (80.5, 29.5), (78.0, 31.0)])
BOX = box(70.0, 15.0, 137.0, 55.0)


def load():
    with open(src_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    by = {}
    for feat in data["features"]:
        p = feat["properties"]
        if p.get("Type") == "POLITY" and feat.get("geometry"):
            by.setdefault(p["Name"], []).append(feat)
    return by


by_name = load()


def geom_at(name, year):
    rows = [f for f in by_name.get(name, []) if f["properties"]["FromYear"] <= year <= f["properties"]["ToYear"]]
    if not rows:
        raise SystemExit(f"no row for {name} @ {year}")
    return shape(rows[0]["geometry"]).buffer(0)


def rings_of(g, tol):
    g = g.intersection(BOX).buffer(0)
    polys = [g] if isinstance(g, Polygon) else list(getattr(g, "geoms", []))
    out = []
    for p in polys:
        if not isinstance(p, Polygon) or p.area < 0.3:
            continue
        s = p.simplify(tol if p.area > 50 else tol / 2, preserve_topology=True)
        if s.is_empty:
            continue
        for q in ([s] if isinstance(s, Polygon) else list(s.geoms)):
            coords = [[round(x, 2), round(y, 2)] for x, y in q.exterior.coords]
            if len(coords) >= 4:
                out.append(coords)
    return out


out = {}
for layer, (year, picks) in TARGETS.items():
    parts = []
    for name, zh in picks:
        g = geom_at(name, year)
        if layer == "ming":
            g = unary_union([g, geom_at("Qing Dynasty", 1820).intersection(PLATEAU)]).buffer(0.02).buffer(-0.02)
        rings = rings_of(g, 0.12)
        if rings:
            parts.append({"n": zh, "r": rings})
    out[layer] = {"y": year, "p": parts}
out["xia"] = {"y": -1700, "p": [{"n": "夏（二里头文化核心区）", "r": rings_of(Polygon(XIA), 0.05)}], "sketch": True}

payload = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
header = """// GENERATED by scripts/build-territories.py — do not edit by hand.
//
// Approximate dynasty territories, one representative year each (schematic, not survey-grade).
// Source: Cliopatria, Seshat Global History Databank — CC BY 4.0
//   https://github.com/Seshat-Global-History-Databank/cliopatria
// Changes made: outer rings only; clipped to 70–137°E / 15–55°N; simplified;
//   明 includes the Tibetan plateau (乌斯藏·朵甘都司) following 谭其骧《中国历史地图集》,
//     taken from Cliopatria's Qing (1820) extent within a plateau outline and merged;
//   夏 is not in the dataset — a hand-sketched 二里头文化 core area (marked sketch).
//
// Shape: { [layerId]: { y: year, p: [{ n: 中文名, r: [[[lng, lat], …], …] }], sketch?: true } }
export const DYNASTY_TERRITORY_JSON = """
with open(out_ts, "w", encoding="utf-8") as f:
    f.write(header + json.dumps(payload, ensure_ascii=False) + "\n")
print("layers:", len(out), "bytes:", len(payload), "points:", sum(len(r) for v in out.values() for p in v["p"] for r in p["r"]))

if preview and china_path:
    china = json.load(open(china_path, "r", encoding="utf-8"))
    cg = shape(china["features"][0]["geometry"]).buffer(0)
    china_rings = rings_of(cg, 0.1)
    X0, X1, Y0, Y1 = 66, 140, 12, 57
    W, H, cols = 330, 200, 4
    order = ["xia"] + list(TARGETS.keys())

    def path(rings, ox, oy):
        d = []
        for r in rings:
            pts = [(ox + (x - X0) / (X1 - X0) * W, oy + (Y1 - y) / (Y1 - Y0) * H) for x, y in r]
            d.append("M" + " L".join(f"{a:.1f},{b:.1f}" for a, b in pts) + " Z")
        return " ".join(d)

    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{cols * (W + 10)}" height="{math.ceil(len(order) / cols) * (H + 30)}" style="background:#fff;font-family:sans-serif">']
    pal = ["#c0392b", "#2471a3", "#1e8449"]
    for i, layer in enumerate(order):
        ox, oy = (i % cols) * (W + 10), (i // cols) * (H + 30) + 20
        svg.append(f'<text x="{ox + 4}" y="{oy - 5}" font-size="13">{layer} · {out[layer]["y"]}</text>')
        svg.append(f'<rect x="{ox}" y="{oy}" width="{W}" height="{H}" fill="#f7f7f2" stroke="#ccc"/>')
        svg.append(f'<path d="{path(china_rings, ox, oy)}" fill="none" stroke="#999" stroke-width="0.7"/>')
        for k, part in enumerate(out[layer]["p"]):
            c = pal[k % len(pal)]
            svg.append(f'<path d="{path(part["r"], ox, oy)}" fill="{c}" fill-opacity="0.25" stroke="{c}" stroke-width="1"/>')
    svg.append("</svg>")
    with open(preview, "w", encoding="utf-8") as f:
        f.write("\n".join(svg))
